async function appendData() {
  try {
    console.log("Appending extra data to existing topics...");
    for (const [topicId, points] of Object.entries(extraData)) {
      const docRef = doc(db, "topics", topicId);
      await updateDoc(docRef, {
        content: arrayUnion(...points)
      });
      console.log(`Added ${points.length} points to ${topicId}`);
    }
    console.log("Successfully appended all extra data!");
    process.exit(0);
  } catch (err) {
    console.error("Error appending data:", err);
    process.exit(1);
  }
}

appendData();
